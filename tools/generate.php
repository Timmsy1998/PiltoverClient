<?php

// Keep named methods, contracts, endpoint documentation and OpenAPI in sync with the reviewed catalogue.
$root = dirname(__DIR__);
$catalogue = json_decode(file_get_contents($root . '/resources/riot-endpoints.json'), true, 512, JSON_THROW_ON_ERROR);
$version = trim(file_get_contents($root . '/VERSION'));
$trait = "<?php\n\nnamespace Timmsy\\PiltoverClient\\Http;\n\n/** Generated by tools/generate.php. */\ntrait LeagueEndpoints\n{\n";
$contract = "<?php\n\nnamespace Timmsy\\PiltoverClient\\Contracts;\n\n/** Generated by tools/generate.php. */\ninterface RiotClientContract\n{\n    public function ping(): string;\n    public function endpoints(): array;\n    public function call(string \$endpoint, array \$path = [], array \$query = [], ?array \$body = null): mixed;\n";
$docs = "# Endpoint catalogue\n\nReviewed against [Riot's reference](https://developer.riotgames.com/apis/) on 2026-10-08.\n\nUse named methods or `call(operationId, path, query, body)`. Query arrays are optional except where Riot requires a parameter. Tournament helpers take body then query; updates take code then body.\n\n| Operation ID | PHP method | HTTP | Route | Authentication |\n| --- | --- | --- | --- | --- |\n";
$spec = ['openapi' => '3.1.0', 'info' => ['title' => 'PiltoverClient Riot endpoint reference', 'version' => $version,
    'description' => 'Remote Riot APIs, not routes exposed by your Laravel application. Response DTOs are defined in Riot documentation.'],
    'servers' => [['url' => 'https://{platform}.api.riotgames.com', 'variables' => ['platform' => ['default' => 'euw1']]]],
    'paths' => [], 'components' => ['securitySchemes' => ['apiKey' => ['type' => 'apiKey', 'in' => 'header', 'name' => 'X-Riot-Token'],
    'rso' => ['type' => 'http', 'scheme' => 'bearer']]]];
foreach ($catalogue as $id => $endpoint) {
    preg_match_all('/{(\w+)}/', $endpoint['path'], $matches);
    $arguments = []; $values = []; $parameters = [];
    foreach ($matches[1] as $key) {
        $variable = $key === 'encryptedPUUID' ? 'puuid' : $key;
        $arguments[] = (in_array($key, ['championId', 'challengeId', 'tournamentId'], true) ? 'int|string $' : 'string $') . $variable;
        $values[] = "'{$key}' => \${$variable}";
        $parameters[] = ['name' => $key, 'in' => 'path', 'required' => true, 'schema' => ['type' => 'string']];
    }
    if ($endpoint['body']) {
        $arguments[] = 'array $body';
    }
    if ($endpoint['query']) {
        $arguments[] = 'array $params = []';
    }
    foreach ($endpoint['query'] as $query) {
        $parameters[] = ['name' => $query['name'], 'in' => 'query', 'required' => $query['required'], 'schema' => ['type' => 'string']];
    }
    $signature = 'public function ' . $endpoint['helper'] . '(' . implode(', ', $arguments) . '): ' . ($endpoint['return'] === 'null' ? 'mixed' : $endpoint['return']);
    $contract .= "    {$signature};\n";
    $trait .= "    {$signature}\n    {\n        return \$this->call('{$id}', [" . implode(', ', $values) . '], ' . ($endpoint['query'] ? '$params' : '[]') . ', ' . ($endpoint['body'] ? '$body' : 'null') . ");\n    }\n\n";
    $docs .= "| `{$id}` | `{$endpoint['helper']}()` | {$endpoint['method']} `{$endpoint['path']}` | {$endpoint['route']} | {$endpoint['auth']} |\n";
    $operation = ['operationId' => $id, 'summary' => $endpoint['helper'], 'tags' => [explode('.', $id)[0]],
        'security' => [[$endpoint['auth'] === 'rso' ? 'rso' : 'apiKey' => []]], 'parameters' => $parameters,
        'responses' => ['200' => ['description' => 'Riot JSON response; see official DTO documentation.'], '204' => ['description' => 'Successful empty response.'],
        '429' => ['description' => 'Rate limited; respect Retry-After.'], 'default' => ['description' => 'Riot error.']]];
    if ($endpoint['route'] !== 'platform') {
        $region = $endpoint['route'] === 'tournament' ? 'americas' : 'europe';
        $operation['servers'] = [['url' => $endpoint['route'] === 'tournament' ? 'https://americas.api.riotgames.com' : 'https://{regional}.api.riotgames.com',
            'variables' => $endpoint['route'] === 'tournament' ? new stdClass() : ['regional' => ['default' => $region]]]];
    }
    if ($endpoint['body']) {
        $operation['requestBody'] = ['required' => true, 'content' => ['application/json' => ['schema' => ['type' => 'object', 'additionalProperties' => true]]]];
    }
    $spec['paths'][$endpoint['path']][strtolower($endpoint['method'])] = $operation;
}
file_put_contents($root . '/src/Http/LeagueEndpoints.php', $trait . "}\n");
file_put_contents($root . '/src/Contracts/RiotClientContract.php', $contract . "}\n");
file_put_contents($root . '/docs/endpoints.md', $docs);
file_put_contents($root . '/resources/openapi/openapi.json', json_encode($spec, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n");
